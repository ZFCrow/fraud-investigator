def _environment_url():
    """The app's own database, when DB_HOST is set in the process environment --
    i.e. inside a container, where Compose injects .env. On the host .env is not
    exported (and names the in-network host `db`), so alembic.ini's URL is used."""
    if not os.environ.get("DB_HOST"):
        return None
    from shared.database.service import database_url
    return database_url("postgresql+psycopg2")

